// Generates components/CATALOG.md content from per-component schema.json files.
// Invoked by scripts/generate-catalog-md.sh:
//   node scripts/lib/generate-catalog-md.mjs <components-dir>
import { pathToFileURL } from 'node:url';
import { listComponentNames, loadSchema, renderFields } from './component-schema.mjs';

export function renderCatalog(dir) {
  let out = '# Component Catalog\n\n';
  out += '> Generated by scripts/generate-catalog-md.sh — do not edit by hand.\n';
  out += '> The agent reads this file when authoring build-plan.yaml to learn what components exist.\n\n';
  out += 'A page in build-plan.yaml is a list of components stacked vertically.\n';
  out += 'Each component has a `type` field naming one of the entries below.\n\n';
  out += '---\n\n';

  for (const name of listComponentNames(dir)) {
    const schema = loadSchema(dir, name);
    out += '## ' + name + '\n\n';
    out += (schema.description || '_no description_') + '\n\n';
    out += renderFields(schema);
  }

  return out.trimEnd() + '\n';
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const [dir] = process.argv.slice(2);
  if (!dir) {
    console.error('Usage: node generate-catalog-md.mjs <components-dir>');
    process.exit(2);
  }
  process.stdout.write(renderCatalog(dir));
}
