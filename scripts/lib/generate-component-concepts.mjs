// Generates the OKF Component concept bundle under docs/knowledge/components/
// from per-component schema.json files — one concept file per component, plus an
// index. Generated from the same schemas as components/CATALOG.md (via
// component-schema.mjs), so the two representations stay in lockstep.
//
//   node scripts/lib/generate-component-concepts.mjs <components-dir> <out-dir>
import fs from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { listComponentNames, loadSchema, renderFields } from './component-schema.mjs';

const GENERATED_NOTE =
  '<!-- Generated by scripts/generate-catalog-md.sh — do not edit by hand. -->';

// JSON.stringify yields a safe double-quoted YAML scalar for these strings
// (titles/descriptions never contain control characters).
function yamlString(value) {
  return JSON.stringify(value);
}

export function renderConceptFile(name, schema) {
  const description = schema.description || ('The ' + name + ' component.');
  let out = '---\n';
  out += 'type: Component\n';
  out += 'title: ' + yamlString(name) + '\n';
  out += 'description: ' + yamlString(description) + '\n';
  out += 'tags: [components]\n';
  out += '---\n\n';
  out += GENERATED_NOTE + '\n\n';
  out += '# ' + name + '\n\n';
  out += description + '\n\n';
  out += renderFields(schema);
  return out.trimEnd() + '\n';
}

export function renderConceptIndex(names) {
  let out = '---\n';
  out += 'type: Guide\n';
  out += 'title: Component Concepts\n';
  out += 'description: OKF Component concepts generated from component schemas. The agent-facing authoring vocabulary lives in components/CATALOG.md.\n';
  out += 'tags: [components, okf, index]\n';
  out += '---\n\n';
  out += GENERATED_NOTE + '\n\n';
  out += '# Component Concepts\n\n';
  out += 'One OKF `Component` concept per built-in component, generated from\n';
  out += '`components/<name>/schema.json`. For the agent-facing authoring vocabulary,\n';
  out += 'see [`components/CATALOG.md`](../../../components/CATALOG.md).\n\n';
  out += names.map((n) => '- [' + n + '](' + n + '.md)').join('\n') + '\n';
  return out;
}

// Writes the bundle, returning the relative paths written. Removes stale
// concept files for components that no longer exist.
export function generateConcepts(componentsDir, outDir) {
  const names = listComponentNames(componentsDir);
  fs.mkdirSync(outDir, { recursive: true });

  const expected = new Set(['index.md', ...names.map((n) => n + '.md')]);
  for (const existing of fs.readdirSync(outDir)) {
    if (existing.endsWith('.md') && !expected.has(existing)) {
      fs.rmSync(path.join(outDir, existing));
    }
  }

  fs.writeFileSync(path.join(outDir, 'index.md'), renderConceptIndex(names));
  for (const name of names) {
    fs.writeFileSync(path.join(outDir, name + '.md'), renderConceptFile(name, loadSchema(componentsDir, name)));
  }
  return [...expected].sort();
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const [componentsDir, outDir] = process.argv.slice(2);
  if (!componentsDir || !outDir) {
    console.error('Usage: node generate-component-concepts.mjs <components-dir> <out-dir>');
    process.exit(2);
  }
  const written = generateConcepts(componentsDir, outDir);
  console.log('✓ ' + outDir + ': ' + written.length + ' Component concept file(s)');
}
